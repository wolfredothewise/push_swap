#include "ft_printf.h"

int	ft_putstr(char *s)
{
	int	j;

	if (s == NULL)
		return (ft_putstr("(null)"));
	j = 0;
	while (*s != '\0')
	{
		write(1, s, 1);
		s++;
		j++;
	}
	return (j);
}
